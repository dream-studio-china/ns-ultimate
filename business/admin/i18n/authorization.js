/** Returns the localized value only when the code has an explicit translation. */
export function translatedAuthorizationName(kind, code, locale) {
  if (typeof code !== 'string' || code === '') return null
  const value = authorizationNameMessages[locale]?.[`${kind}.${code}`]
  return typeof value === 'string' && value !== '' ? value : null
}

/**
 * Resolve a display name for a permission or role code.
 * Unknown codes and the English locale fall back to the API-provided name so
 * custom entries and canonical seed labels remain visible unchanged.
 */
export function localizedAuthorizationName(kind, code, fallback, locale) {
  const translated = translatedAuthorizationName(kind, code, locale)
  if (translated !== null) return translated
  if (typeof fallback === 'string' && fallback !== '') return fallback
  return typeof code === 'string' ? code : ''
}
